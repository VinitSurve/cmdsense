"""Optional opt-in AI backend integration for CmdSense.

Supports local Ollama or OpenAI-compatible endpoints using standard library urllib.
STRICT PRIVACY AND SAFETY:
1. Default disabled (ai_enabled=False).
2. Requires explicit --ai flag per command.
3. Requires ai_send_confirmed=True if endpoint is non-loopback.
4. Redacts secrets prior to transmission.
5. Treats AI response as untrusted text; runs safety analysis on generated commands;
   NEVER executes anything.
"""

from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from dataclasses import dataclass
from typing import Any
from urllib.parse import urlparse

from cmdsense.common.exceptions import SafetyError
from cmdsense.common.safety import redact_text
from cmdsense.safety import SafetyReport, analyze_safety


@dataclass(frozen=True)
class AIResponse:
    provider: str
    model: str
    content: str
    suggested_commands: list[str]
    safety_reports: list[SafetyReport]
    disclaimer: str = (
        "AI-Generated Content: This text was generated by an AI model and must be "
        "treated as untrusted advice. CmdSense never executes AI-suggested commands automatically."
    )


def is_loopback(endpoint_url: str) -> bool:
    parsed = urlparse(endpoint_url)
    hostname = (parsed.hostname or "").lower()
    return hostname in ("localhost", "127.0.0.1", "::1")


def query_ai(
    prompt: str,
    *,
    config: dict[str, Any],
    system_prompt: str = "You are a helpful macOS / POSIX command line assistant.",
) -> AIResponse:
    """Query configured AI backend with secrets redacted. Raises SafetyError or AIResponse."""
    if not config.get("ai_enabled"):
        raise SafetyError(
            "AI features are disabled in configuration.",
            hint="Run 'cmdsense config set ai_enabled true' and configure provider settings.",
        )

    provider = config.get("ai_provider", "none")
    if provider == "none":
        raise SafetyError(
            "AI provider is set to 'none'.",
            hint="Run 'cmdsense config set ai_provider ollama' or 'openai-compatible'.",
        )

    endpoint = config.get("ai_endpoint", "http://localhost:11434")
    if not is_loopback(endpoint) and not config.get("ai_send_confirmed"):
        raise SafetyError(
            f"Sending data to non-loopback AI endpoint ({endpoint}) is not confirmed.",
            hint="Run 'cmdsense config set ai_send_confirmed true' after reviewing disclosure.",
        )

    timeout = float(config.get("ai_timeout", 15.0))
    model = str(config.get("ai_model", "llama3.2"))
    api_key_env = str(config.get("ai_api_key_env", "OPENAI_API_KEY"))
    api_key = os.environ.get(api_key_env, "").strip()

    # Redact prompt before sending over the network
    safe_prompt = redact_text(prompt)

    if provider == "ollama":
        url = endpoint.rstrip("/") + "/api/generate"
        payload = {
            "model": model,
            "prompt": f"{system_prompt}\n\nTask: {safe_prompt}",
            "stream": False,
        }
        headers = {"Content-Type": "application/json"}
    elif provider == "openai-compatible":
        url = endpoint.rstrip("/") + "/v1/chat/completions"
        payload = {
            "model": model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": safe_prompt},
            ],
            "temperature": 0.2,
        }
        headers = {"Content-Type": "application/json"}
        if api_key:
            headers["Authorization"] = f"Bearer {api_key}"
    else:
        raise SafetyError(f"Unsupported AI provider: {provider}")

    parsed_url = urlparse(url)
    if parsed_url.scheme not in ("http", "https"):
        raise SafetyError(f"Unsupported AI endpoint scheme: {parsed_url.scheme}")

    req_data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=req_data, headers=headers, method="POST")  # noqa: S310

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310
            resp_body = resp.read().decode("utf-8")
            data = json.loads(resp_body)
    except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as exc:
        raise SafetyError(
            f"AI query failed ({provider} at {endpoint}): {exc}",
            hint="Check if the local Ollama or AI server is running.",
        ) from exc

    # Extract text content
    if provider == "ollama":
        content = data.get("response", "")
    else:
        choices = data.get("choices", [])
        if choices and "message" in choices[0]:
            content = choices[0]["message"].get("content", "")
        else:
            content = str(data)

    # Scan response for command lines and run safety analyzer on them
    extracted_cmds: list[str] = _extract_command_candidates(content)
    safety_reports = [analyze_safety(c) for c in extracted_cmds]

    return AIResponse(
        provider=provider,
        model=model,
        content=content,
        suggested_commands=extracted_cmds,
        safety_reports=safety_reports,
    )


def _extract_command_candidates(text: str) -> list[str]:
    """Extract code block or backtick lines that look like shell commands."""
    candidates: list[str] = []
    # Markdown code blocks
    for block in re.findall(r"```(?:bash|sh|zsh)?\n(.*?)```", text, re.DOTALL):
        for line in block.strip().splitlines():
            clean = line.strip().lstrip("$ ")
            if clean and not clean.startswith("#"):
                candidates.append(clean)
    # Inline backticks
    if not candidates:
        for inline in re.findall(r"`([^`\n]+)`", text):
            clean = inline.strip().lstrip("$ ")
            if clean:
                candidates.append(clean)
    return candidates[:5]  # Cap candidate analysis
